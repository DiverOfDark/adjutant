    fn two_pages(head: &str) -> (u16, String) {
        let first_line = head.lines().next().unwrap_or("");
        if first_line.contains("/rest/api/3/myself") {
            return (200, r#"{"displayName":"Ann Lee"}"#.into());
        }
        if !first_line.contains("/rest/api/3/search/jql") {
            return (404, "{}".into());
        }
        if first_line.contains("nextPageToken=PAGE2") {
            (
                200,
                serde_json::json!({
                    "issues": [{"key": "ABC-200", "fields": {"summary": "Second page", "status": {"name": "Done", "statusCategory": {"key": "done"}}}}],
                    "isLast": true
                })
                .to_string(),
            )
        } else {
            let mut page = sample_page();
            page["nextPageToken"] = "PAGE2".into();
            (200, page.to_string())
        }
    }

    #[tokio::test]
    async fn sync_against_mock_server_follows_pages() {
        let (base, seen) = mock_server(two_pages).await;
        let dir = tempfile::tempdir().unwrap();
        let cache = sync(dir.path(), &cfg(&base), "tok").await.unwrap();

        assert_eq!(cache.queries["mine"], vec!["ABC-123", "ABC-124", "ABC-200"]);
        assert_eq!(cache.issues["ABC-200"].status_category, "done");
        assert_eq!(
            cache.issues["ABC-123"].url,
            format!("{base}/browse/ABC-123")
        );

        let reqs = seen.lock().unwrap().clone();
        assert_eq!(reqs.len(), 2);
        let first = reqs[0].to_ascii_lowercase();
        assert!(first.contains("jql=assignee"));
        assert!(first.contains("maxresults=100"));
        assert!(first.contains("fields=summary%2cstatus"));
        // base64("me@example.com:tok")
        assert!(first.contains("authorization: basic bwvazxhhbxbszs5jb206dg9r"));
        assert!(first.contains("user-agent: adjutant/"));

        let loaded = load_cache(dir.path()).unwrap().unwrap();
        assert_eq!(loaded, cache);
        let md = std::fs::read_to_string(dir.path().join(SNAPSHOT_PATH)).unwrap();
        assert!(md.contains("[ABC-200]"));
        assert!(std::fs::read_dir(dir.path().join("jira")).unwrap().count() == 2);

        assert_eq!(
            test_connection(&cfg(&base), "tok").await.unwrap(),
            "Ann Lee"
        );
    }

