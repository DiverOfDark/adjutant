//! Jira Cloud sync: runs the configured JQL queries over the REST API and
//! writes `jira/cache.json` (for the UI) and `jira/snapshot.md` (for agents
//! and humans). Read-only; nothing here writes to Jira.

use std::collections::BTreeMap;
use std::path::Path;
use std::time::Duration;

use anyhow::{Context, anyhow, bail};
use chrono::{DateTime, Local, Utc};
use serde::{Deserialize, Serialize};
use serde_json::Value;

use crate::config::JiraConfig;
use crate::scheduler::atomic_write;

pub const CACHE_PATH: &str = "jira/cache.json";
pub const SNAPSHOT_PATH: &str = "jira/snapshot.md";

/// Query used when `[jira].queries` is empty.
pub const DEFAULT_QUERY_NAME: &str = "mine";
pub const DEFAULT_QUERY: &str =
    "assignee = currentUser() AND resolution = Unresolved ORDER BY updated DESC";

const FIELDS: &str = "summary,status,issuetype,priority,assignee,updated,duedate";
const PAGE_SIZE: usize = 100;
const MAX_PER_QUERY: usize = 500;

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct JiraIssue {
    pub key: String,
    pub summary: String,
    pub status: String,
    /// `new` | `indeterminate` | `done` (Jira's status category key).
    pub status_category: String,
    pub issue_type: Option<String>,
    pub priority: Option<String>,
    pub assignee: Option<String>,
    pub updated: Option<String>,
    pub due: Option<String>,
    /// `{base}/browse/{key}`
    pub url: String,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct JiraCache {
    pub synced_at: DateTime<Utc>,
    pub base_url: String,
    /// All issues from all queries, by key.
    pub issues: BTreeMap<String, JiraIssue>,
    /// Query name -> issue keys in query order.
    pub queries: BTreeMap<String, Vec<String>>,
}

/// Reads `jira/cache.json`; `None` if it has never been synced.
pub fn load_cache(vault: &Path) -> anyhow::Result<Option<JiraCache>> {
    let path = vault.join(CACHE_PATH);
    match std::fs::read_to_string(&path) {
        Ok(text) => serde_json::from_str(&text)
            .map(Some)
            .with_context(|| format!("parsing {}", path.display())),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(None),
        Err(e) => Err(e).with_context(|| format!("reading {}", path.display())),
    }
}

/// Runs every configured query and writes the cache and snapshot.
pub async fn sync(vault: &Path, cfg: &JiraConfig, token: &str) -> anyhow::Result<JiraCache> {
    let base = normalize_base(&cfg.base_url)?;
    check_credentials(cfg, token)?;
    let client = client()?;

    let queries: BTreeMap<String, String> = if cfg.queries.is_empty() {
        BTreeMap::from([(DEFAULT_QUERY_NAME.to_string(), DEFAULT_QUERY.to_string())])
    } else {
        cfg.queries.clone()
    };

    let mut cache = JiraCache {
        synced_at: Utc::now(),
        base_url: base.clone(),
        issues: BTreeMap::new(),
        queries: BTreeMap::new(),
    };
    for (name, jql) in &queries {
        let issues = run_query(&client, &base, &cfg.email, token, jql)
            .await
            .with_context(|| format!("Jira query `{name}` failed"))?;
        let keys = issues.iter().map(|i| i.key.clone()).collect();
        for issue in issues {
            cache.issues.insert(issue.key.clone(), issue);
        }
        cache.queries.insert(name.clone(), keys);
    }
    cache.synced_at = Utc::now();

    let json = serde_json::to_string_pretty(&cache)?;
    atomic_write(&vault.join(CACHE_PATH), json.as_bytes())?;
    atomic_write(
        &vault.join(SNAPSHOT_PATH),
        render_snapshot(&cache).as_bytes(),
    )?;
    Ok(cache)
}

/// Quick credential check; returns the account's display name.
pub async fn test_connection(cfg: &JiraConfig, token: &str) -> anyhow::Result<String> {
    let base = normalize_base(&cfg.base_url)?;
    check_credentials(cfg, token)?;
    let json = get_json(
        &client()?,
        &base,
        &format!("{base}/rest/api/3/myself"),
        &[],
        &cfg.email,
        token,
    )
    .await?;
    json.get("displayName")
        .and_then(Value::as_str)
        .or_else(|| json.get("emailAddress").and_then(Value::as_str))
        .map(str::to_string)
        .ok_or_else(|| anyhow!("unexpected response from Jira /myself (no displayName)"))
}

/// Renders `jira/snapshot.md`.
pub fn render_snapshot(cache: &JiraCache) -> String {
    let mut out = String::new();
    out.push_str("# Jira snapshot\n\n");
    out.push_str(&format!(
        "Synced: {}\n\n",
        cache
            .synced_at
            .with_timezone(&Local)
            .format("%Y-%m-%dT%H:%M:%S%:z")
    ));
    out.push_str("> Generated by Adjutant every 15 minutes. Do not edit.\n");

    // `mine` first, then the rest alphabetically.
    let mut names: Vec<&String> = cache.queries.keys().collect();
    names.sort_by_key(|n| (n.as_str() != DEFAULT_QUERY_NAME, n.as_str()));
    for name in names {
        out.push_str(&format!("\n## {}\n\n", one_line(name)));
        let keys = &cache.queries[name];
        if keys.is_empty() {
            out.push_str("_No issues._\n");
            continue;
        }
        out.push_str("| Key | Summary | Status | Assignee | Updated | Due |\n");
        out.push_str("| --- | --- | --- | --- | --- | --- |\n");
        for key in keys {
            let Some(i) = cache.issues.get(key) else {
                continue;
            };
            let updated = i
                .updated
                .as_deref()
                .map(|u| u.get(..10).unwrap_or(u))
                .unwrap_or("");
            out.push_str(&format!(
                "| [{}]({}) | {} | {} | {} | {} | {} |\n",
                cell(&i.key),
                i.url,
                cell(&i.summary),
                cell(&i.status),
                cell(i.assignee.as_deref().unwrap_or("Unassigned")),
                cell(updated),
                cell(i.due.as_deref().unwrap_or("")),
            ));
        }
    }
    out
}

fn one_line(s: &str) -> String {
    s.replace(['\r', '\n'], " ")
}

fn cell(s: &str) -> String {
    one_line(s).replace('|', "\\|")
}

/// Parses one `/rest/api/3/search/jql` page.
fn parse_page(base_url: &str, json: &Value) -> anyhow::Result<(Vec<JiraIssue>, Option<String>)> {
    let raw = json
        .get("issues")
        .and_then(Value::as_array)
        .ok_or_else(|| anyhow!("unexpected Jira search response (no `issues` array)"))?;
    let base = base_url.trim_end_matches('/');
    let mut issues = Vec::with_capacity(raw.len());
    for item in raw {
        let key = item
            .get("key")
            .and_then(Value::as_str)
            .ok_or_else(|| anyhow!("Jira issue without a key"))?
            .to_string();
        let f = item.get("fields").unwrap_or(&Value::Null);
        let s = |v: &Value| v.as_str().map(str::to_string);
        let name = |field: &str, prop: &str| f.get(field).and_then(|v| v.get(prop)).and_then(s);
        let status = f.get("status").unwrap_or(&Value::Null);
        issues.push(JiraIssue {
            url: format!("{base}/browse/{key}"),
            summary: f.get("summary").and_then(s).unwrap_or_default(),
            status: status.get("name").and_then(s).unwrap_or_default(),
            status_category: status
                .get("statusCategory")
                .and_then(|c| c.get("key"))
                .and_then(s)
                .unwrap_or_else(|| "new".into()),
            issue_type: name("issuetype", "name"),
            priority: name("priority", "name"),
            assignee: name("assignee", "displayName"),
            updated: f.get("updated").and_then(s),
            due: f.get("duedate").and_then(s),
            key,
        });
    }
    let is_last = json.get("isLast").and_then(Value::as_bool).unwrap_or(false);
    let next = json
        .get("nextPageToken")
        .and_then(Value::as_str)
        .filter(|t| !t.is_empty() && !is_last)
        .map(str::to_string);
    Ok((issues, next))
}

async fn run_query(
    client: &reqwest::Client,
    base: &str,
    email: &str,
    token: &str,
    jql: &str,
) -> anyhow::Result<Vec<JiraIssue>> {
    let url = format!("{base}/rest/api/3/search/jql");
    let max = PAGE_SIZE.to_string();
    let mut all = Vec::new();
    let mut page_token: Option<String> = None;
    loop {
        let mut query = vec![("jql", jql), ("fields", FIELDS), ("maxResults", &max)];
        if let Some(t) = &page_token {
            query.push(("nextPageToken", t));
        }
        let json = get_json(client, base, &url, &query, email, token).await?;
        let (issues, next) = parse_page(base, &json)?;
        all.extend(issues);
        if all.len() >= MAX_PER_QUERY {
            all.truncate(MAX_PER_QUERY);
            break;
        }
        match next {
            Some(t) if Some(&t) != page_token.as_ref() => page_token = Some(t),
            _ => break,
        }
    }
    Ok(all)
}

async fn get_json(
    client: &reqwest::Client,
    base: &str,
    url: &str,
    query: &[(&str, &str)],
    email: &str,
    token: &str,
) -> anyhow::Result<Value> {
    let resp = client
        .get(url)
        .query(query)
        .basic_auth(email, Some(token))
        .header(reqwest::header::ACCEPT, "application/json")
        .send()
        .await
        .map_err(|e| network_error(base, &e))?;
    let status = resp.status();
    let body = resp.text().await.map_err(|e| network_error(base, &e))?;
    if status.is_success() {
        return serde_json::from_str(&body)
            .with_context(|| format!("Jira returned invalid JSON (HTTP {status})"));
    }
    let messages = jira_messages(&body);
    match status.as_u16() {
        401 | 403 => bail!(
            "Jira rejected the credentials (HTTP {}): check email and API token{}",
            status.as_u16(),
            suffix(&messages)
        ),
        400 => bail!(
            "Jira rejected the request (HTTP 400){}",
            if messages.is_empty() {
                format!(": {}", snippet(&body))
            } else {
                format!(": {messages}")
            }
        ),
        404 => bail!(
            "Jira endpoint not found (HTTP 404): check the base URL ({base}){}",
            suffix(&messages)
        ),
        429 => bail!("Jira rate limit hit (HTTP 429); will retry on the next sync"),
        _ => bail!(
            "Jira request failed (HTTP {status}){}",
            if messages.is_empty() {
                format!(": {}", snippet(&body))
            } else {
                format!(": {messages}")
            }
        ),
    }
}

fn suffix(messages: &str) -> String {
    if messages.is_empty() {
        String::new()
    } else {
        format!(" ({messages})")
    }
}

/// Collects Jira's `errorMessages` and `errors` into one line.
fn jira_messages(body: &str) -> String {
    let Ok(json) = serde_json::from_str::<Value>(body) else {
        return String::new();
    };
    let mut out: Vec<String> = json
        .get("errorMessages")
        .and_then(Value::as_array)
        .map(|a| {
            a.iter()
                .filter_map(Value::as_str)
                .map(str::to_string)
                .collect()
        })
        .unwrap_or_default();
    if let Some(errors) = json.get("errors").and_then(Value::as_object) {
        for (field, msg) in errors {
            if let Some(m) = msg.as_str() {
                out.push(format!("{field}: {m}"));
            }
        }
    }
    out.join("; ")
}

fn snippet(body: &str) -> String {
    let t = body.trim();
    if t.is_empty() {
        return "empty response".into();
    }
    let s: String = t.chars().take(200).collect();
    if s.len() < t.len() {
        format!("{s}…")
    } else {
        s
    }
}

fn network_error(base: &str, e: &reqwest::Error) -> anyhow::Error {
    let mut msg = e.to_string();
    let mut src = std::error::Error::source(e);
    while let Some(s) = src {
        msg.push_str(": ");
        msg.push_str(&s.to_string());
        src = s.source();
    }
    if e.is_timeout() {
        anyhow!("Jira at {base} did not respond within 30 seconds ({msg})")
    } else {
        anyhow!("could not reach Jira at {base}: {msg}")
    }
}

fn client() -> anyhow::Result<reqwest::Client> {
    reqwest::Client::builder()
        .timeout(Duration::from_secs(30))
        .user_agent(concat!("adjutant/", env!("CARGO_PKG_VERSION")))
        .build()
        .context("creating HTTP client")
}

fn check_credentials(cfg: &JiraConfig, token: &str) -> anyhow::Result<()> {
    if cfg.email.trim().is_empty() {
        bail!("Jira email is not set in [jira] email");
    }
    if token.trim().is_empty() {
        bail!("Jira API token is not set; add it in Settings");
    }
    Ok(())
}

/// Trims trailing slashes and adds `https://` when the scheme is missing.
fn normalize_base(base: &str) -> anyhow::Result<String> {
    let b = base.trim().trim_end_matches('/');
    if b.is_empty() {
        bail!("Jira base URL is not set in [jira] base_url");
    }
    if b.starts_with("http://") || b.starts_with("https://") {
        Ok(b.to_string())
    } else {
        Ok(format!("https://{b}"))
    }
}

